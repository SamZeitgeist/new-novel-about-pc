/* helpers для условий по сборке */
function pickPart(state, cat) {
  const isLaptop = state && (state.mode === 'laptop' || window.__VN_MODE === 'laptop');
  const parts = isLaptop ? (window.PARTS_LAPTOP || window.PARTS) : (window.PARTS || {});
  const list = (parts && parts[cat]) || [];
  return list.find(p => p.id === state.build[cat]) || null;
}

function mbIs(state, prop, value) {
  const p = pickPart(state, 'mb');
  return !!p && p[prop] === value;
}

function gpuIs(state, prop, value) {
  const p = pickPart(state, 'gpu');
  return !!p && p[prop] === value;
}

